import {spawnSync} from 'node:child_process';
import {readdirSync,readFileSync,mkdirSync,writeFileSync,renameSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {evaluationReport} from './evaluation-report.mjs';
const startedAt=new Date().toISOString();
const files=readdirSync('tests').filter(n=>n.endsWith('.test.ts')).sort().map(n=>'tests/'+n);
const result=spawnSync(process.execPath,['--experimental-strip-types','--test','--test-reporter=tap',...files],{encoding:'utf8',maxBuffer:20*1024*1024});
const log=result.stdout+'\n'+result.stderr;
const report=evaluationReport(log,result.status??1,startedAt,new Date().toISOString());
const paths=['src/case-agent','src/server/case-agent','scripts/evidence-mcp','tests'];
const sourceFiles=paths.flatMap(p=>readdirSync(p).filter(n=>/\.(ts|mjs)$/.test(n)).map(n=>p+'/'+n)).sort();
report.sourceHashes=Object.fromEntries(sourceFiles.map(p=>[p,createHash('sha256').update(readFileSync(p)).digest('hex')]));
report.breakdown={retained:134,unified:report.total-134};
mkdirSync('verification/evaluation-runs',{recursive:true});
report.logPath='verification/evaluation-runs/'+report.runId+'.tap';
writeFileSync(report.logPath,log);
writeFileSync('verification/evaluation-runs/'+report.runId+'.json',JSON.stringify(report,null,2));
writeFileSync('verification/evaluations-current.tmp',JSON.stringify(report,null,2));
renameSync('verification/evaluations-current.tmp','verification/evaluations-current.json');
console.log(JSON.stringify({runId:report.runId,outcome:report.outcome,total:report.total,passed:report.passed,failed:report.failed,checks:report.checks.length,logPath:report.logPath}));
process.exitCode=report.outcome==='passed'?0:1;
